-- Tiger Woods Game Report table - one row per player of a head-to-head match (both players report the same match)
CREATE TABLE IF NOT EXISTS stats.TW_GAME_REPORT (
    GAME_CONNECTION_ID bigint PRIMARY KEY NOT NULL,
    SIDE numeric NOT NULL DEFAULT 0,                    -- player index in the report (fields suffixed 0 or 1)
    RNK numeric NOT NULL DEFAULT 0,                     -- ranked or not
    DONE numeric NOT NULL DEFAULT 0,                    -- round completed (0/1)
    QUIT numeric NOT NULL DEFAULT 0,                    -- quit (0/1)
    TYPE numeric NOT NULL DEFAULT 0,                    -- ?
    SCORE numeric NOT NULL DEFAULT 0,                   -- holes up in Match Play
    CLUB numeric NOT NULL DEFAULT 0,                    -- ?
    STROKES numeric NOT NULL DEFAULT 0,                 -- strokes
    PUTTS numeric NOT NULL DEFAULT 0,                   -- putts
    HOLES numeric NOT NULL DEFAULT 0,                   -- holes played
    EAGS numeric NOT NULL DEFAULT 0,                    -- eagles
    BIRD numeric NOT NULL DEFAULT 0,                    -- birdies
    ACES numeric NOT NULL DEFAULT 0,                    -- holes in one
    GIR numeric NOT NULL DEFAULT 0,                     -- greens in regulation
    LPUT numeric NOT NULL DEFAULT 0,                    -- longest putt holed (feet)
    DRVS numeric NOT NULL DEFAULT 0,                    -- drives
    FRWY numeric NOT NULL DEFAULT 0,                    -- fairways hit
    LDRV numeric NOT NULL DEFAULT 0,                    -- longest drive (yards)
    SHTC numeric NOT NULL DEFAULT 0,                    -- ?
    PARS numeric NOT NULL DEFAULT 0,                    -- pars
    SBOG numeric NOT NULL DEFAULT 0,                    -- bogeys
    DBOG numeric NOT NULL DEFAULT 0,                    -- double bogeys
    TBOG numeric NOT NULL DEFAULT 0,                    -- triple bogeys or worse
    COMP numeric NOT NULL DEFAULT 0,                    -- ?
    CONSTRAINT FK_TW_GAME_REPORT_GAME_CONNECTION_ID FOREIGN KEY (GAME_CONNECTION_ID) REFERENCES core.GAME_CONNECTION(ID)
);

-- Tiger Woods Persona Stats table - aggregated online statistics, updated when a result is received
CREATE TABLE IF NOT EXISTS stats.TW_PERSONA_STATS (
    ID bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY NOT NULL,
    PERSONA_ID bigint NOT NULL,
    VERS varchar(32) NOT NULL,
    MATCH_POINTS numeric NOT NULL DEFAULT 0,            -- 2 per win, 1 per tie
    MATCH_WINS numeric NOT NULL DEFAULT 0,
    MATCH_LOSSES numeric NOT NULL DEFAULT 0,
    MATCH_TIES numeric NOT NULL DEFAULT 0,
    MATCH_STREAK numeric NOT NULL DEFAULT 0,            -- current streak, negative when losing
    MATCH_COMPLETE numeric NOT NULL DEFAULT 0,
    MATCH_INCOMPLETE numeric NOT NULL DEFAULT 0,
    STROKE_POINTS numeric NOT NULL DEFAULT 0,
    STROKE_WINS numeric NOT NULL DEFAULT 0,
    STROKE_LOSSES numeric NOT NULL DEFAULT 0,
    STROKE_TIES numeric NOT NULL DEFAULT 0,
    STROKE_STREAK numeric NOT NULL DEFAULT 0,
    STROKE_COMPLETE numeric NOT NULL DEFAULT 0,
    STROKE_INCOMPLETE numeric NOT NULL DEFAULT 0,
    HOLES numeric NOT NULL DEFAULT 0,                   -- golf from completed matches and counted tournament rounds
    PUTTS numeric NOT NULL DEFAULT 0,
    PUTT_HOLES numeric NOT NULL DEFAULT 0,              -- holes whose putts were reported
    GIR numeric NOT NULL DEFAULT 0,
    GIR_HOLES numeric NOT NULL DEFAULT 0,               -- holes whose greens in regulation were reported
    FAIRWAYS numeric NOT NULL DEFAULT 0,
    DRIVES numeric NOT NULL DEFAULT 0,                  -- drives whose fairways were reported
    EAGLES numeric NOT NULL DEFAULT 0,
    BIRDIES numeric NOT NULL DEFAULT 0,
    ACES numeric NOT NULL DEFAULT 0,
    LONGEST_PUTT numeric NOT NULL DEFAULT 0,
    LONGEST_DRIVE numeric NOT NULL DEFAULT 0,
    ROUNDS numeric NOT NULL DEFAULT 0,                  -- full 18-hole rounds with a stroke total
    ROUND_STROKES numeric NOT NULL DEFAULT 0,
    ROUND_BIRDIES numeric NOT NULL DEFAULT 0,
    BEST_ROUND numeric NULL,
    EVENTS numeric NOT NULL DEFAULT 0,                  -- tournaments entered
    EVENT_WINS numeric NOT NULL DEFAULT 0,
    TOP10 numeric NOT NULL DEFAULT 0,
    TOP25 numeric NOT NULL DEFAULT 0,
    EARNINGS bigint NOT NULL DEFAULT 0,                 -- prize money in dollars
    CONSTRAINT FK_TW_PERSONA_STATS_PERSONA_ID FOREIGN KEY (PERSONA_ID) REFERENCES core.PERSONA(ID),
    CONSTRAINT UK_TW_PERSONA_STATS_PERSONA_VERS UNIQUE (PERSONA_ID, VERS)
);

-- Tiger Woods tournament calendar - one event per day, days count from 1899-12-30 like the game
CREATE TABLE IF NOT EXISTS stats.TW_EVENT (
    ID bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY NOT NULL,
    VERS varchar(32) NOT NULL,
    EVENT_DAY numeric NOT NULL,
    NAME varchar(32) NOT NULL,
    COURSE numeric NOT NULL,
    PURSE bigint NOT NULL,
    CONDITIONS numeric NOT NULL,                        -- tees, rough, fairways and greens bits
    SERIES_START numeric NULL,                          -- first day of a multi-day event
    SETTLED_ON timestamp NULL,                          -- when the day's results were ranked and paid
    CONSTRAINT UK_TW_EVENT_VERS_DAY UNIQUE (VERS, EVENT_DAY)
);

-- Tiger Woods tournament rounds - a start key issued by the server, then the scorecard
CREATE TABLE IF NOT EXISTS stats.TW_ENTRY (
    ID bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY NOT NULL,
    TOKEN varchar(32) NOT NULL,
    EVENT_ID bigint NOT NULL,
    PERSONA_ID bigint NOT NULL,
    START_TIME timestamp NOT NULL,
    END_TIME timestamp NULL,                            -- when the scorecard was received
    COUNTED boolean NOT NULL DEFAULT false,             -- a completed round on the leaderboard (multi-day events: the day's first start)
    RNK numeric NULL,
    DONE numeric NULL,
    QUIT numeric NULL,
    TYPE numeric NULL,
    SCORE numeric NULL,
    CLUB numeric NULL,
    STROKES numeric NULL,
    PUTTS numeric NULL,
    HOLES numeric NULL,
    EAGS numeric NULL,
    BIRD numeric NULL,
    ACES numeric NULL,
    GIR numeric NULL,
    LPUT numeric NULL,
    DRVS numeric NULL,
    FRWY numeric NULL,
    LDRV numeric NULL,
    SHTC numeric NULL,
    PARS numeric NULL,
    SBOG numeric NULL,
    DBOG numeric NULL,
    TBOG numeric NULL,
    COMP numeric NULL,
    FINAL_RANK numeric NULL,                            -- place in the event, set when its last day is settled
    PRIZE bigint NULL,
    CONSTRAINT UK_TW_ENTRY_TOKEN UNIQUE (TOKEN),
    CONSTRAINT FK_TW_ENTRY_EVENT_ID FOREIGN KEY (EVENT_ID) REFERENCES stats.TW_EVENT(ID),
    CONSTRAINT FK_TW_ENTRY_PERSONA_ID FOREIGN KEY (PERSONA_ID) REFERENCES core.PERSONA(ID)
);
CREATE INDEX IF NOT EXISTS IDX_TW_ENTRY_EVENT_ID ON stats.TW_ENTRY (EVENT_ID);
CREATE INDEX IF NOT EXISTS IDX_TW_ENTRY_PERSONA_ID ON stats.TW_ENTRY (PERSONA_ID);

-- Tiger Woods created golfer, uploaded by the game and shown to other players
CREATE TABLE IF NOT EXISTS stats.TW_GOLFER (
    ID bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY NOT NULL,
    PERSONA_ID bigint NOT NULL,
    VERS varchar(32) NOT NULL,
    DATA text NOT NULL,                                 -- $hex golfer
    UPDATED_ON timestamp NOT NULL,
    CONSTRAINT FK_TW_GOLFER_PERSONA_ID FOREIGN KEY (PERSONA_ID) REFERENCES core.PERSONA(ID),
    CONSTRAINT UK_TW_GOLFER_PERSONA_VERS UNIQUE (PERSONA_ID, VERS)
);

