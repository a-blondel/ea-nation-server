-- Make GAME.PARAMS nullable (some games define the params in the userset instead)
ALTER TABLE core.GAME ALTER COLUMN PARAMS DROP NOT NULL;

-- Create USER_SET table
CREATE TABLE IF NOT EXISTS core.USER_SET (
    ID bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY NOT NULL,
    VERS varchar(64) NOT NULL,
    NAME varchar(128) NOT NULL,
    DESCRIPTION varchar(256) NULL,
    PARAMS text NULL,
    SYSFLAGS varchar(32) NULL,
    CUSTFLAGS varchar(32) NULL,
    SIZE numeric NOT NULL DEFAULT 4,
    TYPE numeric NOT NULL DEFAULT 0,
    UPDATES numeric NOT NULL DEFAULT 0,
    OWNER_ID bigint NULL,
    START_TIME timestamp NOT NULL,
    END_TIME timestamp NULL,
    CONSTRAINT FK_USER_SET_OWNER_ID FOREIGN KEY (OWNER_ID) REFERENCES core.PERSONA(ID)
);

-- Create USER_SET_MEMBER table for tracking players in a UserSet
CREATE TABLE IF NOT EXISTS core.USER_SET_MEMBER (
    ID bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY NOT NULL,
    USER_SET_ID bigint NOT NULL,
    PERSONA_ID bigint NOT NULL,
    SLOT numeric NOT NULL DEFAULT 0,
    START_TIME timestamp NOT NULL,
    END_TIME timestamp NULL,
    CONSTRAINT FK_USER_SET_MEMBER_USER_SET_ID FOREIGN KEY (USER_SET_ID) REFERENCES core.USER_SET(ID),
    CONSTRAINT FK_USER_SET_MEMBER_PERSONA_ID FOREIGN KEY (PERSONA_ID) REFERENCES core.PERSONA(ID)
);

-- Create indexes for common queries
CREATE INDEX IF NOT EXISTS IDX_USER_SET_VERS_END_TIME ON core.USER_SET(VERS, END_TIME);
CREATE INDEX IF NOT EXISTS IDX_USER_SET_NAME_VERS_END_TIME ON core.USER_SET(NAME, VERS, END_TIME);
CREATE INDEX IF NOT EXISTS IDX_USER_SET_MEMBER_USER_SET_ID_END_TIME ON core.USER_SET_MEMBER(USER_SET_ID, END_TIME);
CREATE INDEX IF NOT EXISTS IDX_USER_SET_MEMBER_PERSONA_ID_END_TIME ON core.USER_SET_MEMBER(PERSONA_ID, END_TIME);

